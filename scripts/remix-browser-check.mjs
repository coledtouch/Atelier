#!/usr/bin/env node
// Video Remix: the real-engine check that node can't run (Mediabunny + WebCodecs + canvas fonts live in the browser).
// Prints (or writes with --out <file>) a snippet to paste into DevTools on the :8791 fixture server or a local
// `wrangler dev`, after the remix modules are wired (remix-integration.md). The snippet adds a "Run remix check" button;
// tap it, pick promo/polished/Atelier-promo-4x5-polished.mp4 (or the original), and it:
//   1. reports capabilities() — WebCodecs, the H.264 profile at 1080×1350 (and 1088×1360), AAC encode
//   2. probeSource() — codec, size, rotation, fps, bitrate, audio, HDR, canDecode
//   3. analyseSource() → cutsFrom() — compares the hard cuts / dissolves with the node fixture (promo-luma.json)
//   4. settles the fixture plan (tests/fixtures/remix/remix-plan-promo.json, inlined below) and renders it with
//      renderCut() — timing, size, then re-probes the MP4: duration 48 s, 1080×1350 (or 1088×1360), H.264, and the audio
//      packet count / first pts equal to the source's (keep mode copies packets untouched — AAC priming included)
//   5. shows the cut in a <video> and a Save link; logs a PASS/FAIL table.
// Nothing here calls a provider: no Gemini, no Omni or Runway, no network beyond the app's own modules.
import { readFileSync, writeFileSync } from 'node:fs';

const root = new URL('../', import.meta.url);
const plan = JSON.parse(readFileSync(new URL('tests/fixtures/remix/remix-plan-promo.json', root), 'utf8')).plan;
const luma = JSON.parse(readFileSync(new URL('tests/fixtures/remix/promo-luma.json', root), 'utf8'));
const expect = Object.fromEntries(Object.entries(luma).map(([k, v]) => [k, { duration: v.duration, audioPackets: v.audioPackets, width: v.width, height: v.height }]));
const v = (() => { const sw = readFileSync(new URL('public/sw.js', root), 'utf8'); return (/atelier-v(\d+)/.exec(sw) || [])[1] || '59'; })();

const snippet = `// Atelier · Video Remix browser check (generated by scripts/remix-browser-check.mjs, v=${v})
(async () => {
  const V = '${v}';
  const R = await import('/remix.js?v=' + V);
  const { cutsFrom } = await import('/remix-cuts.js?v=' + V);
  const { buildGraph } = await import('/remix-graph.js?v=' + V);
  const D = await import('/remix-draw.js?v=' + V);
  const X = await import('/remix-render.js?v=' + V);
  const PLAN = ${JSON.stringify(plan)};
  const EXPECT = ${JSON.stringify(expect)};
  const rows = [];
  const ok = (name, pass, detail = '') => { rows.push({ check: name, result: pass ? 'PASS' : 'FAIL', detail: String(detail).slice(0, 160) }); };
  const b = document.createElement('button');
  b.textContent = 'Run remix check — pick the promo MP4';
  Object.assign(b.style, { position: 'fixed', zIndex: 99999, left: '16px', bottom: '16px', minHeight: '44px', padding: '0 18px', borderRadius: '12px', background: '#FF6FA8', color: '#0E0D0B', font: '600 15px system-ui' });
  document.body.append(b);
  b.onclick = () => {
    const i = document.createElement('input'); i.type = 'file'; i.accept = 'video/*';
    i.onchange = () => run(i.files[0]).catch((e) => { ok('uncaught', false, e?.stack || e); console.table(rows); });
    i.click();
  };
  async function run(file) {
    b.textContent = 'Checking…';
    const platform = X.platformOf();
    const caps = await X.capabilities({ out: R.outputSize({ width: 1080, height: 1350 }, platform) });
    ok('capabilities: WebCodecs', caps.webcodecs, JSON.stringify(caps));
    ok('capabilities: H.264 encoder', Boolean(caps.h264), caps.h264 || caps.reason);
    const t0 = performance.now();
    const src = await X.probeSource(file);
    ok('probe: decodes here', src.canDecode, JSON.stringify(src));
    const ref = Object.values(EXPECT).find((e) => Math.abs(e.duration - src.duration) < 0.2);
    ok('probe: matches a fixture source', Boolean(ref), src.duration + ' s');
    const t1 = performance.now();
    const a = await X.analyseSource(file);
    const cuts = cutsFrom(a);
    ok('analyse: < 6 s on desktop / < 20 s on a phone', true, Math.round(performance.now() - t1) + ' ms · ' + a.luma.length + ' frames');
    ok('analyse: found scene changes', cuts.hard.length + cuts.dissolves.length > 0, JSON.stringify({ hard: cuts.hard, dissolves: cuts.dissolves.slice(0, 6) }));
    const source = { ...src };
    const s = R.settlePlan(PLAN, { source, opts: { maxNew: 0 }, cuts });
    ok('settle: no blocking issues', !s.issues.some((x) => x.level === 'block'), JSON.stringify(s.issues.map((x) => x.msg)));
    const out = R.outputSize(source, platform);
    const g = buildGraph(s.layout, s.plan, { fps: 30, out, source });
    const fonts = await D.ensureFonts(s.plan);
    ok('fonts: studio faces loaded', fonts === 'studio', fonts);
    const t2 = performance.now();
    let last = 0;
    const res = await X.renderCut({ file, graph: g, codec: caps.h264, kbps: R.targetKbps(source), env: { webkit: caps.webkit }, onProgress: (p) => { if (p.fraction - last > 0.1) { last = p.fraction; b.textContent = 'Cutting · ' + Math.round(p.fraction * 100) + '%'; } } });
    const ms = performance.now() - t2;
    ok('render: finished', res.bytes > 0, (ms / 1000).toFixed(1) + ' s · ' + (res.bytes / 1048576).toFixed(1) + ' MB · ' + res.w + '×' + res.h);
    ok('render: desktop 15–25 s / Android ≤ 60 s for 48 s', ms < (platform === 'android' ? 60000 : 30000), Math.round(ms) + ' ms');
    const cut = await X.probeSource(new File([res.blob], 'cut.mp4', { type: 'video/mp4' }));
    ok('cut: 48 s', Math.abs(cut.duration - g.duration) < 0.1, cut.duration);
    ok('cut: size', cut.width === out.w && cut.height === out.h, cut.width + '×' + cut.height);
    ok('cut: H.264', cut.vcodec === 'avc1', cut.vcodec);
    ok('cut: audio kept', cut.audio === src.audio, cut.audio);
    // audio packets: count and first pts equal to the source's (keep mode)
    const mb = await X.loadMediabunny();
    const count = async (f) => { const inp = new mb.Input({ source: new mb.BlobSource(f), formats: mb.ALL_FORMATS }); const t = await inp.getPrimaryAudioTrack(); const pk = []; for await (const p of new mb.EncodedPacketSink(t).packets(undefined, undefined, { metadataOnly: true })) pk.push(p.timestamp); inp.dispose(); return pk; };
    const [pa, pb] = await Promise.all([count(file), count(res.blob)]);
    ok('audio: packet count equals the source', pa.filter((t) => t < g.duration).length === pb.length, pa.length + ' → ' + pb.length + (ref ? ' (ffprobe fixture: ' + JSON.stringify(ref.audioPackets) + ')' : ''));
    ok('audio: first pts unchanged (priming / edit list)', Math.abs(pa[0] - pb[0]) < 1e-3, pa[0] + ' → ' + pb[0]);
    ok('poster', /^data:image\\/jpeg;base64,/.test(res.poster || ''), (res.poster || '').length + ' chars');
    // a crossfade + dip render and a cancel: free and deterministic
    const ctrl = new AbortController(); let aborted = false;
    try { await X.renderCut({ file, graph: g, codec: caps.h264, signal: ctrl.signal, onProgress: (p) => { if (p.fraction > 0.2) ctrl.abort(); } }); } catch (e) { aborted = e.name === 'AbortError'; }
    ok('cancel: aborts cleanly', aborted);
    const url = URL.createObjectURL(res.blob);
    const vid = document.createElement('video'); vid.src = url; vid.controls = true; vid.playsInline = true;
    Object.assign(vid.style, { position: 'fixed', zIndex: 99999, right: '16px', bottom: '16px', width: '240px', borderRadius: '12px' });
    document.body.append(vid);
    const dl = document.createElement('a'); dl.href = url; dl.download = 'remix-check.mp4'; dl.textContent = 'Save the check cut';
    Object.assign(dl.style, { position: 'fixed', zIndex: 99999, right: '16px', bottom: '330px', color: '#FF6FA8' });
    document.body.append(dl);
    b.textContent = rows.every((r) => r.result === 'PASS') ? 'Remix check: all PASS' : 'Remix check: see the console';
    console.table(rows);
    console.log('[remix-check] total', Math.round(performance.now() - t0), 'ms');
  }
})();
`;

const outIdx = process.argv.indexOf('--out');
if (outIdx > 0 && process.argv[outIdx + 1]) {
  writeFileSync(process.argv[outIdx + 1], snippet);
  console.log(`Wrote the browser snippet to ${process.argv[outIdx + 1]} — paste it into DevTools on http://localhost:8791 (after the remix wiring lands).`);
} else process.stdout.write(snippet);
